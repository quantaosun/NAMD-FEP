FEP_TCL_CONTENT = """\
# fep.tcl — runFEP procedure for NAMD alchemical FEP
# Runs multiple lambda windows sequentially within a single NAMD job.
# Usage in .namd file:  source ../fep.tcl
#                        runFEP <lambda_start> <lambda_end> <delta_lambda> <nsteps>

proc runFEP {lambda_start lambda_end dlambda nsteps} {
    set n_lambda [expr {int(($lambda_end - $lambda_start) / $dlambda + 0.5)}]
    for {set i 0} {$i < $n_lambda} {incr i} {
        set lambda1 [expr {$lambda_start + $i * $dlambda}]
        set lambda2 [expr {$lambda_start + ($i + 1) * $dlambda}]
        if {$lambda2 > $lambda_end} {set lambda2 $lambda_end}
        alchLambda  $lambda1
        alchLambda2 $lambda2
        print "Running FEP window: lambda $lambda1 -> $lambda2"
        run $nsteps
    }
}

proc runFEPmin {lambda_start lambda_end dlambda nsteps minsteps temp} {
    set n_lambda [expr {int(($lambda_end - $lambda_start) / $dlambda + 0.5)}]
    for {set i 0} {$i < $n_lambda} {incr i} {
        set lambda1 [expr {$lambda_start + $i * $dlambda}]
        set lambda2 [expr {$lambda_start + ($i + 1) * $dlambda}]
        if {$lambda2 > $lambda_end} {set lambda2 $lambda_end}
        alchLambda  $lambda1
        alchLambda2 $lambda2
        print "Running FEP window (min): lambda $lambda1 -> $lambda2"
        minimize $minsteps
        reinitvels $temp
        run $nsteps
    }
}
"""


def write_fep_tcl(output_dir: Path) -> Path:
    """Write the fep.tcl helper to the given directory."""
    path = output_dir / "fep.tcl"
    path.write_text(FEP_TCL_CONTENT)
    return path
