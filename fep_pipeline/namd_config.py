"""
NAMD configuration file generation for FEP simulations.

Generates:
  - NVT equilibration config
  - NPT equilibration config
  - Forward FEP production config (λ: 0 → 1)
  - Backward FEP production config (λ: 1 → 0)
  - Per-window independent configs for HPC submission

Based on the NAMD FEP tutorial workflow: single config with runFEP Tcl
procedure for desktop/small-cluster, or independent window configs for
batch submission.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Optional

# ---------------------------------------------------------------------------
# Lambda schedule
# ---------------------------------------------------------------------------

# Recommended 16-window schedule: denser spacing near endpoints where
# dE/dλ changes most rapidly (electrostatics decoupling).
DEFAULT_LAMBDA_SCHEDULE = [
    0.0000, 0.0450, 0.0900, 0.14546, 0.22425, 0.30303,
    0.38182, 0.46061, 0.5394, 0.61819, 0.6970,
    0.77576, 0.85455, 0.9100, 0.9550, 1.0000,
]


def lambda_windows(n_windows: int = 16) -> list[tuple[float, float]]:
    """Generate (λ_i, λ_{i+1}) window pairs.

    If n_windows matches the default 16, uses the recommended uneven
    schedule. Otherwise uses even spacing.
    """
    if n_windows < 2:
        raise ValueError("Need at least 2 lambda states")
    if n_windows == len(DEFAULT_LAMBDA_SCHEDULE):
        lambdas = DEFAULT_LAMBDA_SCHEDULE
    else:
        step = 1.0 / (n_windows - 1)
        lambdas = [round(i * step, 10) for i in range(n_windows)]
    return [(lambdas[i], lambdas[i + 1]) for i in range(n_windows - 1)]


# ---------------------------------------------------------------------------
# Template rendering
# ---------------------------------------------------------------------------

def render_template(template: str, **kwargs) -> str:
    """Replace @KEY@ placeholders in a template string."""
    result = template
    for key, value in kwargs.items():
        marker = f"@{key.upper()}@"
        result = result.replace(marker, str(value))
    unresolved = [w for w in result.split() if w.startswith("@") and w.endswith("@")]
    if unresolved:
        raise ValueError(f"Unresolved template markers: {unresolved}")
    return result


